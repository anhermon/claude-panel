#!/usr/bin/env node
// Mirrors the two fixtures (web/sample-state.json: the card page, web/sample-stage-state.json: the stage
// page) into tests/fixture-state.ts (a test cannot import JSON). Run it after a fixture changes;
// `--check` fails on drift.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const FIXTURES = [
  ['FIXTURE', 'web/sample-state.json'],
  ['FIXTURE_STAGE', 'web/sample-stage-state.json'],
]
const target = join(root, 'tests/fixture-state.ts')
const body = ([name, file]) =>
  `export const ${name}: PanelState = ${JSON.stringify(JSON.parse(readFileSync(join(root, file), 'utf8')), null, 2)}\n`
const out = `// GENERATED by scripts/gen-fixture.mjs from ${FIXTURES.map(f => f[1]).join(' and ')}. Do not edit.
import type { PanelState } from '../types'

${FIXTURES.map(body).join('\n')}`
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch {}
  if (current !== out) {
    console.error('tests/fixture-state.ts is stale: run node scripts/gen-fixture.mjs')
    process.exit(1)
  }
  console.log('fixture mirror is current')
} else {
  writeFileSync(target, out)
  console.log(`wrote ${target}`)
}
