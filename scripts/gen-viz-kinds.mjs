#!/usr/bin/env node
// Writes hooks/viz-kinds.ts from the asset registry: { kind: { shape, keys } }. The TypeScript side (hooks/board-frames.ts, hooks/spec.ts)
// imports this module for the `viz` frame's valid kinds and the tool description, and web/assets.test.mjs fails when it is stale.
//   node scripts/gen-viz-kinds.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ASSETS, kinds } from '../web/kit/assets/index.js';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'hooks', 'viz-kinds.ts');
export const kindsJson = () => `// GENERATED by scripts/gen-viz-kinds.mjs from the asset registry (web/kit/assets). Do not edit; rerun the script.\n// A .ts module because the host only loads hooks imports named like code.\nexport const VIZ_KIND_TABLE: Record<string, { shape: string; keys: string[] }> = ${JSON.stringify(Object.fromEntries(kinds().map((k) => [k, { shape: ASSETS[k].def.shape, keys: ASSETS[k].def.keys }])), null, 2)}\n`;
if (import.meta.url === `file://${process.argv[1]}`) { writeFileSync(OUT, kindsJson()); console.log(`wrote ${OUT} (${kinds().length} kinds)`); }
