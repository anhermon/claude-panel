// The test sandbox cannot read files, and JSON is not code to its loader, so
// tests/fixture.test.ts imports a generated copy of the two fixtures (the card page's
// web/sample-state.json and the stage page's web/sample-stage-state.json).
//   node tests/sync-fixture.mjs           regenerate tests/fixture-data.ts
//   node tests/sync-fixture.mjs --check   exit 1 if the copy is stale
import { readFileSync, writeFileSync } from 'node:fs'

const FIXTURES = [
  ['FIXTURE', '../web/sample-state.json'],
  ['STAGE_FIXTURE', '../web/sample-stage-state.json'],
]
const TARGET = new URL('./fixture-data.ts', import.meta.url)
const CHECK_FLAG = '--check'

const body = ([name, file]) =>
  `export const ${name}: Record<string, unknown> = ${JSON.stringify(JSON.parse(readFileSync(new URL(file, import.meta.url), 'utf8')), null, 2)}\n`
const out =
  `// GENERATED by tests/sync-fixture.mjs from ${FIXTURES.map(f => f[1].replace('../', '')).join(' and ')}. Do not edit.\n` +
  FIXTURES.map(body).join('')

if (process.argv.includes(CHECK_FLAG)) {
  let current = ''
  try {
    current = readFileSync(TARGET, 'utf8')
  } catch {}
  if (current !== out) {
    console.error('tests/fixture-data.ts is stale: run node tests/sync-fixture.mjs')
    process.exit(1)
  }
} else writeFileSync(TARGET, out)
